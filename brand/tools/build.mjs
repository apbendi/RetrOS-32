/*
 * Renders the whole kit: every asset in tools/catalog.mjs and every
 * composition in examples/, as SVG and PNG, plus assets/favicon.ico,
 * assets/manifest.json and the gallery, index.html.
 *
 *   node tools/build.mjs            # everything
 *   node tools/build.mjs --no-png   # SVGs, manifest and gallery only (no Chrome)
 *   node tools/build.mjs app-icon racing ...   # only these ids
 *
 * Output is deterministic: rebuilding without changes changes no SVG.
 */
import fs from 'node:fs';
import path from 'node:path';
import { CATALOG, SECTIONS } from './catalog.mjs';
import { openRasterizer, ico } from './lib/raster.mjs';
import { docSize, esc, PALETTE, RAMPS } from './lib/core.mjs';
import { loadComposition } from './render.mjs';

const ROOT = path.resolve(path.dirname(new URL(import.meta.url).pathname), '..');
const args = process.argv.slice(2);
const noPng = args.includes('--no-png');
const only = args.filter((a) => !a.startsWith('--'));

// The PNG files an entry asks for: [{ file, w, h }].
function pngTargets(entry, size) {
  const spec = entry.png || {};
  const out = [];
  for (const s of spec.scales || []) {
    out.push({ file: `${entry.path}${s === 1 ? '' : `@${s}x`}.png`, w: Math.round(size.w * s), h: Math.round(size.h * s) });
  }
  for (const w of spec.sizes || []) {
    out.push({ file: `${entry.path}-${w}.png`, w, h: Math.round((size.h * w) / size.w) });
  }
  return out;
}

async function examples() {
  const dir = path.join(ROOT, 'examples');
  const files = fs.readdirSync(dir).filter((f) => f.endsWith('.mjs')).sort();
  const out = [];
  for (const f of files) {
    const c = await loadComposition(path.join(dir, f));
    out.push({
      id: `example-${f.replace(/\.mjs$/, '')}`, section: 'examples', path: `examples/${f.replace(/\.mjs$/, '')}`,
      title: c.meta.title, use: c.meta.use, theme: c.meta.theme, source: `examples/${f}`,
      svg: c.svg, png: c.meta.png || { scales: [1] }, ground: c.meta.ground,
    });
  }
  return out;
}

const main = async () => {
  const all = [...CATALOG, ...(await examples())];
  const ids = new Set();
  for (const e of all) {
    if (ids.has(e.id)) throw new Error(`duplicate id ${e.id}`);
    ids.add(e.id);
  }
  const todo = only.length ? all.filter((e) => only.includes(e.id)) : all;
  if (only.length && todo.length !== only.length) {
    throw new Error(`unknown id: ${only.filter((id) => !ids.has(id)).join(', ')}`);
  }

  const raster = noPng ? null : await openRasterizer();
  const manifest = [];
  try {
    for (const e of all) {
      const svg = e.svg();
      const size = docSize(svg);
      const pngs = pngTargets(e, size);
      if (todo.includes(e)) {
        fs.mkdirSync(path.join(ROOT, path.dirname(e.path)), { recursive: true });
        fs.writeFileSync(path.join(ROOT, `${e.path}.svg`), svg);
        if (raster) {
          for (const p of pngs) fs.writeFileSync(path.join(ROOT, p.file), await raster.png(svg, p.w, p.h));
        }
        process.stdout.write(`${e.id} `);
      }
      manifest.push({
        id: e.id, section: e.section, title: e.title, use: e.use,
        svg: `${e.path}.svg`, size: [size.w, size.h], png: pngs.map((p) => p.file),
        ...(e.source ? { source: e.source } : {}),
      });
    }
    // The favicon: the 16 and the 32 at 32 and 64.
    if (raster && (!only.length || only.includes('app-icon') || only.includes('app-icon-small'))) {
      const small = CATALOG.find((e) => e.id === 'app-icon-small').svg();
      const big = CATALOG.find((e) => e.id === 'app-icon').svg();
      fs.writeFileSync(path.join(ROOT, 'assets/favicon.ico'), ico([
        { size: 16, png: await raster.png(small, 16, 16) },
        { size: 32, png: await raster.png(big, 32, 32) },
        { size: 64, png: await raster.png(big, 64, 64) },
      ]));
    }
  } finally {
    if (raster) await raster.close();
  }
  process.stdout.write('\n');

  fs.writeFileSync(path.join(ROOT, 'assets/manifest.json'), JSON.stringify({
    note: 'Generated by tools/build.mjs from tools/catalog.mjs and examples/. Do not edit.',
    sections: { ...SECTIONS, examples: 'Examples' },
    assets: manifest,
  }, null, 2) + '\n');
  fs.writeFileSync(path.join(ROOT, 'index.html'), gallery(manifest, all));
  console.log(`${todo.length} rendered, ${manifest.length} in the manifest; wrote index.html`);
};

/* ------------------------------------------------------------ the gallery */

function gallery(manifest, all) {
  const byId = Object.fromEntries(all.map((e) => [e.id, e]));
  const sections = { ...SECTIONS, examples: 'Examples' };
  const order = ['mark', 'wordmark', 'lockup', 'sun', 'examples', 'isometric', 'patch', 'badge', 'stripes', 'reference'];
  const card = (m) => {
    const e = byId[m.id];
    const [w, h] = m.size;
    const pixel = fs.readFileSync(path.join(ROOT, m.svg), 'utf8').includes('crispEdges');
    // Fit the preview in its box: whole multiples for pixel art.
    const box = m.section === 'examples' || m.section === 'reference' ? [560, 360] : [300, 200];
    let k = Math.min(box[0] / w, box[1] / h);
    if (pixel && k >= 1) k = Math.floor(k); // whole multiples; smaller previews of big pieces may be uneven
    const files = [`<a href="${m.svg}">SVG</a>`, ...m.png.map((p) => `<a href="${p}">${esc(p.replace(/^.*\//, ''))}</a>`)];
    if (m.source) files.push(`<a href="${m.source}">source</a>`);
    return `<figure class="card${box[0] > 300 ? ' wide' : ''}" id="${m.id}">
  <div class="stage" style="background:${e.ground || PALETTE.blue}"><img src="${m.svg}" width="${Math.round(w * k)}" height="${Math.round(h * k)}" alt="${esc(m.title)}"></div>
  <figcaption><b>${esc(m.title)}</b> <code>${esc(m.id)}</code><p>${esc(m.use || '')}</p><p class="files">${w} × ${h} · ${files.join(' · ')}</p></figcaption>
</figure>`;
  };
  const swatches = Object.entries(PALETTE).map(([k, v]) => `<li><span style="background:${v}"></span><b>${k}</b> ${v}</li>`).join('');
  const ramps = Object.entries(RAMPS).map(([k, r]) => `<li class="ramp"><b>${k}</b>${r.map((v) => `<span title="${v}" style="background:${v}"></span>`).join('')}</li>`).join('');
  const body = order.filter((s) => manifest.some((m) => m.section === s)).map((s) =>
    `<section id="s-${s}"><h2>${esc(sections[s])}</h2><div class="grid">${manifest.filter((m) => m.section === s).map(card).join('\n')}</div></section>`).join('\n');
  return `<!doctype html>
<html lang="en"><head><meta charset="utf-8"><meta name="viewport" content="width=device-width, initial-scale=1">
<title>OgOs brand kit</title>
<link rel="icon" href="assets/favicon.ico">
<!-- Generated by tools/build.mjs. Do not edit. -->
<style>
:root{--blue:${PALETTE.blue};--ink:${PALETTE.ink};--paper:${PALETTE.paper};--cream:${PALETTE.cream};--steel:${PALETTE.steelDark};--orange:${PALETTE.orange}}
*{box-sizing:border-box}
body{margin:0;background:var(--paper);color:var(--ink);font:15px/1.5 system-ui,-apple-system,"Segoe UI",sans-serif}
header{background:var(--blue);color:var(--cream);padding:40px 48px 32px;display:flex;gap:40px;align-items:center;flex-wrap:wrap}
header img{image-rendering:pixelated}
header p{margin:0;max-width:52ch;opacity:.9}
header a{color:var(--cream)}
nav{position:sticky;top:0;z-index:1;background:var(--ink);padding:10px 48px;display:flex;gap:18px;flex-wrap:wrap}
nav a{color:var(--cream);text-decoration:none;font-size:13px}
nav a:hover{color:var(--orange)}
main{padding:8px 48px 64px}
h2{font-size:20px;margin:40px 0 16px;padding-bottom:8px;border-bottom:2px solid var(--ink)}
.grid{display:flex;flex-wrap:wrap;gap:20px}
.card{margin:0;width:340px;background:#fff;border:1px solid #ddd6c4}
.card.wide{width:600px}
.stage{height:240px;display:flex;align-items:center;justify-content:center}
.card.wide .stage{height:400px}
.stage img{image-rendering:pixelated;display:block}
figcaption{padding:12px 14px 14px}
figcaption code{font-size:12px;color:var(--steel)}
figcaption p{margin:6px 0 0;font-size:13px}
.files{color:var(--steel)}
.files a{color:var(--ink)}
.palette{display:flex;flex-wrap:wrap;gap:10px 22px;list-style:none;padding:0;margin:0 0 8px}
.palette li{font-size:13px;display:flex;align-items:center;gap:8px}
.palette span{width:28px;height:28px;border:1px solid #0002;display:inline-block}
.palette .ramp span{width:18px;height:28px;border:0}
.palette .ramp b{margin-right:4px}
</style></head>
<body>
<header>
  <img src="assets/lockup/horizontal-cream.svg" width="412" height="112" alt="OgOs">
  <p>The OgOs brand kit. Read <a href="GUIDE.md">GUIDE.md</a> for how the identity works and <a href="README.md">README.md</a> for how to use and change the kit. Every image here is in <code>assets/</code> or <code>examples/</code>, as SVG and PNG; <code>assets/manifest.json</code> lists them.</p>
</header>
<nav>${order.filter((s) => manifest.some((m) => m.section === s)).map((s) => `<a href="#s-${s}">${esc(sections[s])}</a>`).join('')}<a href="#s-palette">Palette</a></nav>
<main>
${body}
<section id="s-palette"><h2>Palette</h2><ul class="palette">${swatches}</ul><ul class="palette">${ramps}</ul></section>
</main>
</body></html>
`;
}

main().catch((e) => {
  console.error(e);
  process.exit(1);
});
