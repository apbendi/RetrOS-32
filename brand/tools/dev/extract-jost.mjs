/*
 * Regenerates tools/lib/jost-glyphs.mjs from the Jost TTFs in fonts/jost:
 * the outlines, advance widths and kerning of printable ASCII, so the kit
 * can set Jost as SVG paths without loading a font.
 *
 * Only needed when the fonts change. It needs opentype.js, which the kit
 * doesn't otherwise depend on:
 *
 *   npm install --no-save opentype.js@1
 *   node tools/dev/extract-jost.mjs
 */
import fs from 'node:fs';
import path from 'node:path';
import { createRequire } from 'node:module';

const require = createRequire(import.meta.url);
const opentype = require('opentype.js');
const root = path.resolve(path.dirname(new URL(import.meta.url).pathname), '../..');

const WEIGHTS = { 400: 'Jost-400-Book.ttf', 500: 'Jost-500-Medium.ttf', 700: 'Jost-700-Bold.ttf' };
const CHARS = Array.from({ length: 95 }, (_, i) => String.fromCharCode(32 + i));

const out = {};
for (const [weight, file] of Object.entries(WEIGHTS)) {
  const font = opentype.parse(fs.readFileSync(path.join(root, 'fonts/jost', file)).buffer);
  const glyphs = {};
  for (const ch of CHARS) {
    const g = font.charToGlyph(ch);
    // y down, as in SVG, in font units.
    const d = g.getPath(0, 0, font.unitsPerEm).commands.map((c) => {
      const p = (x, y) => `${Math.round(x)} ${Math.round(y)}`;
      if (c.type === 'M' || c.type === 'L') return c.type + p(c.x, c.y);
      if (c.type === 'Q') return 'Q' + p(c.x1, c.y1) + ' ' + p(c.x, c.y);
      if (c.type === 'C') return 'C' + p(c.x1, c.y1) + ' ' + p(c.x2, c.y2) + ' ' + p(c.x, c.y);
      return 'Z';
    }).join('');
    glyphs[ch] = { a: g.advanceWidth, d };
  }
  const kern = {};
  for (const a of CHARS) for (const b of CHARS) {
    const k = font.getKerningValue(font.charToGlyph(a), font.charToGlyph(b));
    if (k) kern[a + b] = k;
  }
  out[weight] = {
    upm: font.unitsPerEm,
    ascender: font.ascender,
    descender: font.descender,
    capHeight: font.tables.os2.sCapHeight,
    xHeight: font.tables.os2.sxHeight,
    glyphs,
    kern,
  };
}

const body =
  '// Generated by tools/dev/extract-jost.mjs from fonts/jost. Do not edit.\n' +
  '// Jost is Copyright 2020 The Jost Project Authors, under the SIL Open Font License 1.1 (fonts/jost/OFL.txt).\n' +
  'export default ' + JSON.stringify(out) + ';\n';
fs.writeFileSync(path.join(root, 'tools/lib/jost-glyphs.mjs'), body);
console.log('wrote tools/lib/jost-glyphs.mjs,', Math.round(body.length / 1024), 'KB;',
  Object.entries(out).map(([w, f]) => `${w}: ${Object.keys(f.kern).length} kerning pairs`).join(', '));
