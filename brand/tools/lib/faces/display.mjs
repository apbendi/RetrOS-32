// Rows 3-13: the x-height and a descender.
const dsc = (...r) => [...blank(r[0].length, 3), ...r];
// Rows from the top, padded to 14.
const top = (...r) => [...r, ...blank(r[0].length, 14 - r.length)];
// n copies of a row.
const x = (row, n) => Array(n).fill(row);

