/*
 * OgOs Label: the compact face, from the old RetrOS logo's name lettering.
 * Upright strokes are two pixels wide and crossbars one pixel tall, and
 * outer corners are cut by one pixel.
 *
 * A glyph is 11 rows: capitals and figures on rows 0-8, small letters'
 * x-height on rows 2-8, ascenders from row 0, descenders on 9-10. Glyphs
 * are 6 columns wide unless their shape needs otherwise (I, M, N, W, i, l,
 * m, w, punctuation...). Zero is slashed, to tell it from O.
 */
const E2 = ['......', '......'];

const blank = (w, n) => Array(n).fill('.'.repeat(w));
// Rows 0-8: capitals, figures, and small letters with ascenders.
const cap = (...r) => [...r, ...blank(r[0].length, 2)];
// Rows 2-8: the x-height.
const xh = (...r) => [...blank(r[0].length, 2), ...r, ...blank(r[0].length, 2)];
// Rows 2-10: the x-height and a descender.
const dsc = (...r) => [...blank(r[0].length, 2), ...r];
// Rows from the top, padded to 11.
const top = (...r) => [...r, ...blank(r[0].length, 11 - r.length)];
// n copies of a row.
const x = (row, n) => Array(n).fill(row);

